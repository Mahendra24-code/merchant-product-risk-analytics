"""
=============================================================================
FINTech Risk Analytics: Multivariate Anomaly Detection & Root-Cause Analysis
=============================================================================
Objective:
1. Aggregate raw hourly transaction data into daily business metrics.
2. Train an Isolation Forest model to detect complex, multivariate anomalies.
3. Compare ML detection against baseline rule-based flags.
4. Use SHAP values to explain the root causes of the detected anomalies.
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.model_selection import train_test_split
import shap
import warnings
import os

warnings.filterwarnings('ignore')

# Set plotting style
sns.set_theme(style="whitegrid")
plt.rcParams['figure.figsize'] = (12, 6)

# Ensure output directories exist
os.makedirs('visuals', exist_ok=True)
os.makedirs('data', exist_ok=True)

# =============================================================================
# STEP 1: Load and Inspect Data
# =============================================================================
print("📂 Step 1: Loading data...")
# Ensure the CSV is in the same directory as this script
file_path = 'merchant_transaction_data.csv'
if not os.path.exists(file_path):
    raise FileNotFoundError(f"Could not find {file_path}. Please ensure the CSV is in the same folder.")

df = pd.read_csv(file_path)

# Convert date columns to datetime using mixed format to handle different string formats safely
df['date'] = pd.to_datetime(df['date'], format='mixed')
df['Transaction_Date'] = pd.to_datetime(df['Transaction_Date'], format='mixed')

print(f"✓ Loaded {len(df)} raw hourly transaction records.")

# =============================================================================
# STEP 2: Data Aggregation (Simulating the SQL Layer)
# =============================================================================
print("\n🔄 Step 2: Aggregating data to daily merchant-category level...")

daily_agg = df.groupby(['Transaction_Date', 'product_category', 'merchant_tier']).agg(
    daily_volume=('transaction_volume', 'sum'),
    avg_risk_score=('risk_score', 'mean'),
    active_merchants=('merchant_id', 'nunique'),
    baseline_anomaly_count=('is_anomaly', 'sum')
).reset_index()

# Sort for time-series feature engineering
daily_agg = daily_agg.sort_values(['product_category', 'merchant_tier', 'Transaction_Date'])

print(f"✓ Aggregated into {len(daily_agg)} daily records.")

# =============================================================================
# STEP 3: Feature Engineering for Machine Learning
# =============================================================================
print("\n🛠️ Step 3: Engineering features for the ML model...")

# Calculate rolling 7-day metrics per category and tier
daily_agg['rolling_7_day_avg_volume'] = daily_agg.groupby(['product_category', 'merchant_tier'])['daily_volume'].transform(
    lambda x: x.rolling(window=7, min_periods=1).mean()
)

daily_agg['rolling_7_day_std_volume'] = daily_agg.groupby(['product_category', 'merchant_tier'])['daily_volume'].transform(
    lambda x: x.rolling(window=7, min_periods=1).std().fillna(0)
)

# Create a "Volume Spike Ratio" (Current volume vs 7-day average)
daily_agg['volume_spike_ratio'] = daily_agg['daily_volume'] / (daily_agg['rolling_7_day_avg_volume'] + 1e-6)

# Handle any infinite values
daily_agg.replace([np.inf, -np.inf], np.nan, inplace=True)
daily_agg.fillna(0, inplace=True)

print("✓ Features engineered: rolling averages, std deviations, and spike ratios.")

# =============================================================================
# STEP 4: Train Isolation Forest Model
# =============================================================================
print("\n🤖 Step 4: Training Isolation Forest model...")

# Define features for the model
features = [
    'daily_volume',
    'avg_risk_score',
    'active_merchants',
    'rolling_7_day_avg_volume',
    'volume_spike_ratio'
]

X = daily_agg[features]

# Initialize and train Isolation Forest
# contamination=0.05 means we expect roughly 5% of the data to be anomalies
iso_forest = IsolationForest(contamination=0.05, random_state=42, n_estimators=100)
daily_agg['ml_anomaly_flag'] = iso_forest.fit_predict(X)

# Convert output: 1 = Normal, -1 = Anomaly -> 0 = Normal, 1 = Anomaly
daily_agg['ml_anomaly_flag'] = daily_agg['ml_anomaly_flag'].map({1: 0, -1: 1})

print("✓ Isolation Forest trained. Anomalies detected.")

# =============================================================================
# STEP 5: Model Comparison & Business Insights
# =============================================================================
print("\n📊 Step 5: Comparing ML Model vs. Baseline Rules...")

# Baseline rule: if baseline_anomaly_count > 0, it's an anomaly
daily_agg['baseline_anomaly_flag'] = (daily_agg['baseline_anomaly_count'] > 0).astype(int)

# Calculate overlap and differences
total_ml_anomalies = daily_agg['ml_anomaly_flag'].sum()
total_baseline_anomalies = daily_agg['baseline_anomaly_flag'].sum()
overlap = ((daily_agg['ml_anomaly_flag'] == 1) & (daily_agg['baseline_anomaly_flag'] == 1)).sum()
ml_only = ((daily_agg['ml_anomaly_flag'] == 1) & (daily_agg['baseline_anomaly_flag'] == 0)).sum()

print(f"   - Total Baseline (Rule-based) Anomalies: {total_baseline_anomalies}")
print(f"   - Total ML (Isolation Forest) Anomalies: {total_ml_anomalies}")
print(f"   - Overlap (Caught by both): {overlap}")
print(f"   - 🎯 NEW Complex Anomalies Caught ONLY by ML: {ml_only}")

# =============================================================================
# STEP 6: Root-Cause Analysis using SHAP
# =============================================================================
print("\n🔍 Step 6: Generating SHAP Root-Cause Analysis...")

# Isolation Forest doesn't have native SHAP support, so we train a Random Forest
# proxy model on the ML flags to extract feature importances via SHAP.
print("   Training Random Forest proxy model for SHAP explainability...")

X_train, X_test, y_train, y_test = train_test_split(X, daily_agg['ml_anomaly_flag'], test_size=0.2, random_state=42)
rf_proxy = RandomForestClassifier(n_estimators=100, random_state=42, class_weight='balanced')
rf_proxy.fit(X_train, y_train)

# Calculate SHAP values
explainer = shap.TreeExplainer(rf_proxy)
shap_values = explainer.shap_values(X_test)

# Extract shap values for class 1 safely across different shap output formats
if isinstance(shap_values, list):
    # For list output
    shap_to_plot = shap_values[1]
elif isinstance(shap_values, np.ndarray) and len(shap_values.shape) == 3:
    # For 3D array output [samples, features, classes]
    shap_to_plot = shap_values[:, :, 1]
else:
    # Fallback to general output structure
    shap_to_plot = shap_values

# Plot SHAP Summary
plt.figure(figsize=(10, 6))
shap.summary_plot(shap_to_plot, X_test, feature_names=features, show=False)
plt.title("SHAP Feature Importance: Drivers of ML-Detected Anomalies", fontsize=14, fontweight='bold')
plt.tight_layout()
plt.savefig('visuals/shap_anomaly_drivers.png', dpi=300, bbox_inches='tight')
print("✓ SHAP summary plot saved to 'visuals/shap_anomaly_drivers.png'")

# =============================================================================
# STEP 7: Export Final Dataset
# =============================================================================
print("\n💾 Step 7: Exporting final scored dataset...")

# Select final columns for the Power BI dashboard
final_output = daily_agg[[
    'Transaction_Date', 'product_category', 'merchant_tier',
    'daily_volume', 'avg_risk_score', 'active_merchants',
    'rolling_7_day_avg_volume', 'baseline_anomaly_flag', 'ml_anomaly_flag'
]].copy()

# Rename for Power BI consistency
final_output.rename(columns={
    'baseline_anomaly_flag': 'is_anomaly',
    'ml_anomaly_flag': 'ml_anomaly_flag'
}, inplace=True)

final_output.to_csv('data/merchant_risk_scored_output.csv', index=False)
print("✓ Final dataset exported to 'data/merchant_risk_scored_output.csv'")

print("\n" + "="*60)
print("🚀 SUCCESS! End-to-end ML Anomaly Detection Complete.")
print("="*60)